"""Input/Output safety guardrails and Human-in-the-Loop (HITL) approval hooks."""

from dataclasses import dataclass
import logging
from typing import Any, Dict, Optional

from enterprise_support_agent.telemetry import PIIRedactor

logger = logging.getLogger("enterprise_support_agent.guardrails")


@dataclass
class GuardrailCheckResult:
    """Structured outcome of an input or output guardrail evaluation."""

    passed: bool
    reason: str
    sanitized_text: Optional[str] = None


class InputGuardrail:
    """Validates incoming user queries against prompt-injection and destructive patterns."""

    PROHIBITED_PATTERNS = (
        "ignore all previous instructions",
        "ignore previous instructions",
        "system prompt override",
        "reveal your system prompt",
        "drop table",
        "rm -rf",
        "delete from ticket_states",
    )

    @classmethod
    def validate(cls, user_query: str) -> GuardrailCheckResult:
        """Verify that the user query is safe, in-scope, and sanitized of PII.

        Args:
            user_query: Raw user message string.

        Returns:
            GuardrailCheckResult indicating pass/fail status and sanitized text.
        """
        if not user_query or not user_query.strip():
            return GuardrailCheckResult(
                passed=False,
                reason="Empty query received. Please provide a valid customer support or data analysis request.",
            )

        normalized = user_query.lower()
        for pattern in cls.PROHIBITED_PATTERNS:
            if pattern in normalized:
                logger.warning(
                    "[InputGuardrail] Blocked prohibited pattern: '%s'", pattern
                )
                return GuardrailCheckResult(
                    passed=False,
                    reason=f"Security Policy Violation: Query contains prohibited instruction pattern ('{pattern}').",
                )

        sanitized = PIIRedactor.redact(user_query)
        return GuardrailCheckResult(
            passed=True,
            reason="Input passed safety and PII guardrails.",
            sanitized_text=sanitized,
        )


class OutputGuardrail:
    """Verifies that agent responses are grounded, non-empty, and free of unredacted PII."""

    @classmethod
    def validate(cls, response_text: str) -> GuardrailCheckResult:
        """Validate and sanitize the final agent response before returning to the user.

        Args:
            response_text: Candidate response generated by the agent or worker.

        Returns:
            GuardrailCheckResult with sanitized output text.
        """
        if not response_text or not response_text.strip():
            return GuardrailCheckResult(
                passed=False,
                reason="Agent produced an empty response.",
            )

        sanitized = PIIRedactor.redact(response_text)
        return GuardrailCheckResult(
            passed=True,
            reason="Output passed quality and PII redaction guardrails.",
            sanitized_text=sanitized,
        )


class HumanInTheLoopHook:
    """Manages human approval gates for high-stakes or destructive support actions."""

    HIGH_STAKES_ACTIONS = {
        "bulk_close_tickets",
        "issue_large_refund",
        "override_sla_policy",
        "delete_customer_record",
    }

    def __init__(self, auto_approve: bool = True) -> None:
        self.auto_approve = auto_approve
        self.pending_approvals: Dict[str, Dict[str, Any]] = {}

    def requires_approval(self, action_name: str, parameters: Dict[str, Any]) -> bool:
        """Check whether an action requires human operator confirmation.

        Args:
            action_name: Name of the tool or operation.
            parameters: Tool call arguments or query metadata.

        Returns:
            True if execution should pause for human approval, False otherwise.
        """
        if self.auto_approve:
            return False
        if action_name in self.HIGH_STAKES_ACTIONS:
            return True
        query_text = str(parameters.get("query", "")).lower()
        if any(
            phrase in query_text
            for phrase in ("bulk close", "delete all", "refund $", "override sla")
        ):
            return True
        return False

    def create_approval_request(
        self,
        request_id: str,
        action_name: str,
        parameters: Dict[str, Any],
    ) -> Dict[str, Any]:
        """Record a pending human approval request and return a structured prompt."""
        sanitized_params = PIIRedactor.redact_dict(parameters)
        record = {
            "request_id": request_id,
            "action_name": action_name,
            "parameters": sanitized_params,
            "status": "pending_human_approval",
            "message": (
                f"High-stakes action '{action_name}' requires explicit human supervisor approval "
                f"before execution (request_id={request_id})."
            ),
        }
        self.pending_approvals[request_id] = record
        return record

    def approve(self, request_id: str) -> Optional[Dict[str, Any]]:
        """Mark a pending HITL request as approved."""
        if request_id in self.pending_approvals:
            self.pending_approvals[request_id]["status"] = "approved"
            return self.pending_approvals[request_id]
        return None


input_guardrail = InputGuardrail()
output_guardrail = OutputGuardrail()
hitl_manager = HumanInTheLoopHook(auto_approve=True)
